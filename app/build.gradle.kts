    //
    // This is the maintained fork of com.jcraft:jsch (identical package names,
    // drop-in replacement). Upstream 0.1.55 is from 2018 and cannot authenticate
    // with RSA keys against OpenSSH 8.8+, which disabled the legacy ssh-rsa
    // (SHA-1) signature; the fork adds rsa-sha2-256/512, ed25519 and modern KEX.
    implementation("com.github.mwiede:jsch:0.2.25")
    // lifecycleScope for MainActivity's coroutines (torn down with the Activity).
    implementation("androidx.lifecycle:lifecycle-runtime-ktx:2.8.7")
